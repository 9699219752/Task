
public class Employee {
	

	    public static void main(String[] args) {

	        // 1. byte
	        byte age = 22;

	        // 2. short
	        short experienceMonths = 18;

	        // 3. int
	        int employeeId = 1001;

	        // 4. long
	        long contactNumber = 9876543210L;

	        // 5. float
	        float performanceRating = 4.5f;

	        // 6. double
	        double salary = 55000.75;

	        // 7. char
	        char grade = 'A';

	        // 8. boolean
	        boolean isPermanent = true;

	        // 9. String (Non-Primitive)
	        String employeeName = "Rahul";

	        // Display values
	        System.out.println("Employee Name: " + employeeName);
	        System.out.println("Employee ID: " + employeeId);
	        System.out.println("Age: " + age);
	        System.out.println("Experience (Months): " + experienceMonths);
	        System.out.println("Contact Number: " + contactNumber);
	        System.out.println("Performance Rating: " + performanceRating);
	        System.out.println("Salary: " + salary);
	        System.out.println("Grade: " + grade);
	        System.out.println("Permanent Employee: " + isPermanent);
	    }
	
}




